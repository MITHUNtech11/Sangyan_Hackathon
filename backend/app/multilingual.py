def build_multilingual_explanation(
    status: OverallStatus,
    en_override: Optional[str] = None,
    ta_override: Optional[str] = None,
    key_takeaway_override: Optional[str] = None,
    custom_translations: Optional[Dict[str, str]] = None
) -> SimpleExplanation:
    """Build a SimpleExplanation with high-fidelity translations across all 11 languages."""
    base_dict = dict(STATUS_EXPLANATIONS.get(status, STATUS_EXPLANATIONS[OverallStatus.NEEDS_VERIFICATION]))

    if custom_translations:
        base_dict.update({k: v for k, v in custom_translations.items() if v})

    en_text = en_override or base_dict.get("en", "")
    ta_text = ta_override or base_dict.get("ta", "")
    base_dict["en"] = en_text
    base_dict["ta"] = ta_text

    takeaway = key_takeaway_override or KEY_TAKEAWAYS.get(status, {}).get("en", "Always verify with official sources.")

    return SimpleExplanation(
        en=en_text,
        ta=ta_text,
        key_takeaway=takeaway,
        translations=base_dict
    )
